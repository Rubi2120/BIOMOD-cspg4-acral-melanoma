# BIOMOD 2026 - Pandora's Box
# Internal expression controls across transcriptomic datasets.
#
# Objective:
# Explore whether differences in CSPG4 expression may partly
# reflect technical variation or differences in cellular composition.
#
# Reference genes: ACTB, GAPDH and TBP.
# Melanocytic markers: MLANA and PMEL.
# Target gene: CSPG4.
#
# This exploratory analysis does not correct study-related
# confounding or establish cellular specificity.
#
# Individual-level expression matrices are restricted inputs.
# Only aggregate results are exported.

local({

  suppressPackageStartupMessages(library(dplyr))

  # Reproduce the original BIOMOD random number configuration.
  RNGkind(
    kind = "L'Ecuyer-CMRG",
    normal.kind = "Inversion",
    sample.kind = "Rejection"
  )

  set.seed(20261022)

  input_root <- getOption(
    "biomod.controls.input_root", "."
  )

  output_dir <- getOption(
    "biomod.controls.output_dir", "tables"
  )

  dir.create(
    output_dir,
    recursive = TRUE,
    showWarnings = FALSE
  )

  # Load matrices generated by the data preparation workflow.

  input_file <- file.path(
    input_root,
    "results_v2/intermedios/ctl_tpm.rds"
  )

  if (!file.exists(input_file)) {
    stop("Missing expression matrices: ", input_file)
  }

  rr <- readRDS(input_file)

  tpm <- rr$tpm
  genes <- rr$genes

  if (!requireNamespace("brunnermunzel", quietly = TRUE)) {
    stop("Required package: brunnermunzel")
  }

  # Brunner-Munzel test.

  bm_p <- function(x, y) {
    brunnermunzel::brunnermunzel.test(x, y)$p.value
  }

  # Cliff's delta: positive values indicate that x tends
  # to have higher expression than y.

  cliff_delta <- function(x, y) {

    r <- rank(c(x, y))
    nx <- length(x)
    ny <- length(y)

    2 * (sum(r[seq_len(nx)]) -
           nx * (nx + 1) / 2) / (nx * ny) - 1
  }

  # Bootstrap confidence intervals with 2,000 resamples.

  bootstrap_ci <- function(x, y, B = 2000) {

    unname(quantile(
      replicate(B, cliff_delta(
        sample(x, replace = TRUE),
        sample(y, replace = TRUE)
      )),
      c(.025, .975)
    ))
  }

  # Within-sample expression percentiles.
  # Use genes shared across all four study groups.
  # Percentiles are calculated among genes with positive TPM.
  # A gene with zero TPM receives a percentile of zero.

  common_genes <- Reduce(
    intersect,
    lapply(tpm, rownames)
  )

  message(
    "Genes shared across the four groups: ",
    length(common_genes)
  )

  gene_percentile <- function(m, gs) {

    m <- m[common_genes, , drop = FALSE]

    out <- apply(m, 2, function(x) {

      v <- x[x > 0]

      vapply(gs, function(id) {
        if (x[id] > 0) mean(v <= x[id]) else 0
      }, numeric(1))

    })

    matrix(
      out,
      nrow = length(gs),
      dimnames = list(names(gs), colnames(m))
    )
  }

  # Construct the internal sample-level dataset.
  # This object is not exported.

  long_data <- bind_rows(lapply(names(tpm), function(gr) {

    P <- gene_percentile(tpm[[gr]], genes)

    bind_rows(lapply(names(genes), function(s) {

      data.frame(
        group = gr,
        gene = s,
        log2 = log2(as.numeric(
          tpm[[gr]][genes[[s]], ]
        ) + 1),
        percentile = as.numeric(P[s, ])
      )

    }))
  }))

  # Aggregate expression summaries.

  summary_table <- long_data |>
    group_by(gene, group) |>
    summarise(
      n = n(),
      median_log2 = median(log2),
      median_percentile = median(percentile),
      .groups = "drop"
    )

  print(as.data.frame(summary_table))

  # Preserve the original comparison and bootstrap order.

  pairs <- list(
    c("G1a", "G3"),
    c("G1b", "G3"),
    c("G2", "G3")
  )

  design <- expand.grid(
    metric = c("log2", "percentile"),
    gene = names(genes),
    pair = seq_along(pairs),
    stringsAsFactors = FALSE
  )

  contrasts <- bind_rows(lapply(
    seq_len(nrow(design)),
    function(i) {

      r <- design[i, ]
      p <- pairs[[r$pair]]

      x <- long_data[[r$metric]][
        long_data$gene == r$gene &
        long_data$group == p[1]
      ]

      y <- long_data[[r$metric]][
        long_data$gene == r$gene &
        long_data$group == p[2]
      ]

      ci <- bootstrap_ci(x, y)

      data.frame(
        metric = r$metric,
        gene = r$gene,
        contrast = paste(p, collapse = " vs "),
        cliff_delta = cliff_delta(x, y),
        CI95_lower = ci[1],
        CI95_upper = ci[2],
        p = bm_p(x, y)
      )

    }
  )) |>
    group_by(metric) |>
    mutate(p_BH = p.adjust(p, "BH")) |>
    ungroup()

  # Multiple-testing adjustment is performed separately
  # within each metric: 18 contrasts per family.

  stopifnot(
    nrow(summary_table) == 24,
    nrow(contrasts) == 36,
    all(table(contrasts$metric) == 18)
  )

  for (metric_name in unique(contrasts$metric)) {

    subset <- contrasts[
      contrasts$metric == metric_name,
    ]

    stopifnot(isTRUE(all.equal(
      subset$p_BH,
      p.adjust(subset$p, "BH"),
      tolerance = 1e-10
    )))
  }

  print(as.data.frame(contrasts))

  # Export aggregate results only.

  write.csv(
    summary_table,
    file.path(
      output_dir,
      "expression_controls_summary.csv"
    ),
    row.names = FALSE
  )

  write.csv(
    contrasts,
    file.path(
      output_dir,
      "expression_controls_contrasts.csv"
    ),
    row.names = FALSE
  )

  message("Aggregate control results saved to: ", output_dir)

  # Interpretation:
  #
  # Consistent CSPG4 differences across expression metrics
  # support the descriptive consistency of the findings.
  #
  # Differences in reference genes indicate that technical
  # and biological effects cannot be reliably separated.
  #
  # MLANA and PMEL provide melanocytic expression context,
  # but do not directly establish cellular composition.
  #
  # Within-sample percentiles depend on the detected genes
  # and are not a batch-effect correction.

})
